/*
 * test_image.c - image decoding (stb_image wrapper) + RGBA-over-white
 * blending unit tests.
 *
 * Console app (built with -bc). Verifies the Task 16 assertions:
 * decoding an embedded 2x2 PNG (red/green/blue/white quadrants) from
 * memory AND from a temp file yields exact pixels; garbage/missing
 * inputs fail cleanly; draw_blend_white is byte-exact - opacity 0 is
 * pure white, 100 is the original colors, 50 is the per-byte
 * round-half-up mix, out-of-range opacity clamps.
 *
 * Prints one "ok ..." line per check and a final "PASS"/"FAIL" line.
 * Exit code: 0 on PASS, 1 on FAIL.
 *
 * Build (see root makefile):
 *   wcl386 -bt=nt -bm -wx -bc -fe=tests\test_image.exe ^
 *          src\tests\test_image.c src\core\image.c src\ui\draw.c ^
 *          src\core\config.c src\core\toml.c src\core\utf.c gdi32.lib
 * (draw.c pulls in ui_font -> g_cfg -> config/toml/utf; gdi32 covers
 * the GDI symbols in draw.obj.)
 */
#include <stdio.h>
#include <string.h>

#include "../core/image.h"
#include "../ui/draw.h"

static int g_fail = 0;

#define CHECK(cond)                                                  \
    do {                                                             \
        if (cond) {                                                  \
            printf("ok %s\n", #cond);                                \
        } else {                                                     \
            printf("FAIL %s (line %d)\n", #cond, __LINE__);          \
            g_fail++;                                                \
        }                                                            \
    } while (0)

/* 2x2 RGBA PNG, 8-bit: row 0 = red, green; row 1 = blue, white.
 * Generated by build\gen_t16png.py (zlib output is deterministic). */
static const unsigned char kPng2x2[] = {
    0x89,0x50,0x4e,0x47,0x0d,0x0a,0x1a,0x0a,0x00,0x00,0x00,0x0d,0x49,0x48,
    0x44,0x52,0x00,0x00,0x00,0x02,0x00,0x00,0x00,0x02,0x08,0x06,0x00,0x00,
    0x00,0x72,0xb6,0x0d,0x24,0x00,0x00,0x00,0x13,0x49,0x44,0x41,0x54,0x78,
    0x9c,0x63,0xf8,0xcf,0xc0,0xf0,0x1f,0x0c,0x19,0x18,0xfe,0x83,0x01,0x00,
    0x49,0xc8,0x09,0xf7,0x14,0x63,0x32,0x9d,0x00,0x00,0x00,0x00,0x49,0x45,
    0x4e,0x44,0xae,0x42,0x60,0x82
};

/* expected RGBA of the four quadrants */
static const unsigned char kQuad[4][4] = {
    { 255, 0,   0,   255 },   /* top-left  red   */
    { 0,   255, 0,   255 },   /* top-right green */
    { 0,   0,   255, 255 },   /* bot-left  blue  */
    { 255, 255, 255, 255 }    /* bot-right white */
};

static int pixels_ok(const unsigned char *rgba)
{
    int p, c;

    if (rgba == NULL)
        return 0;
    for (p = 0; p < 4; p++)
        for (c = 0; c < 4; c++)
            if (rgba[p * 4 + c] != kQuad[p][c])
                return 0;
    return 1;
}

/* exact per-byte mix for the test's hardcoded checks */
static int mix50(int c)
{
    return (c * 50 + 255 * 50 + 50) / 100;
}

int main(void)
{
    unsigned char *rgba = NULL;
    int w = 0, h = 0;
    int r;

    /* --- decode from memory --- */
    r = image_decode_mem(kPng2x2, (int)sizeof kPng2x2, &w, &h, &rgba);
    CHECK(r == 0);
    CHECK(w == 2 && h == 2);
    CHECK(rgba != NULL);
    CHECK(pixels_ok(rgba));
    image_free(rgba);
    rgba = NULL;

    /* --- decode from a temp file --- */
    {
        FILE *fp = fopen("t16_img_tmp.png", "wb");
        int wrote = 0;

        CHECK(fp != NULL);
        if (fp != NULL) {
            wrote = (fwrite(kPng2x2, 1, sizeof kPng2x2, fp)
                     == sizeof kPng2x2);
            fclose(fp);
        }
        CHECK(wrote);
        w = 0; h = 0;
        r = image_decode_file("t16_img_tmp.png", &w, &h, &rgba);
        CHECK(r == 0);
        CHECK(w == 2 && h == 2);
        CHECK(pixels_ok(rgba));
        image_free(rgba);
        rgba = NULL;
        remove("t16_img_tmp.png");
    }

    /* --- failures stay clean --- */
    r = image_decode_file("__t16_no_such.png", &w, &h, &rgba);
    CHECK(r != 0);
    CHECK(rgba == NULL);
    r = image_decode_mem("not an image", 12, &w, &h, &rgba);
    CHECK(r != 0);
    CHECK(rgba == NULL);
    r = image_decode_mem(NULL, 0, &w, &h, &rgba);
    CHECK(r != 0);
    r = image_decode_file("", &w, &h, &rgba);
    CHECK(r != 0);
    image_free(NULL);   /* must be a no-op */

    /* --- draw_blend_white --- */
    {
        unsigned char rgb[12];
        unsigned char rgba2[16];
        int p, c;

        /* opacity 0 -> pure white */
        memset(rgb, 0, sizeof rgb);
        draw_blend_white(kQuad[0], 1, 0, rgb);
        CHECK(rgb[0] == 255 && rgb[1] == 255 && rgb[2] == 255);

        /* opacity 100 -> original colors, alpha ignored */
        for (p = 0; p < 4; p++) {
            memset(rgb, 0, sizeof rgb);
            draw_blend_white(kQuad[p], 1, 100, rgb);
            CHECK(rgb[0] == kQuad[p][0] && rgb[1] == kQuad[p][1]
                  && rgb[2] == kQuad[p][2]);
        }
        memcpy(rgba2, "\x0a\x14\x1e\x00\x01\x02\x03\x04"
                      "\xfe\xfd\xfc\xff\x00\x00\x00\x80", 16);
        memset(rgb, 0, sizeof rgb);
        draw_blend_white(rgba2, 4, 100, rgb);
        CHECK(memcmp(rgb, "\x0a\x14\x1e\x01\x02\x03\xfe\xfd\xfc"
                          "\x00\x00\x00", 12) == 0);

        /* opacity 50 -> per-byte (c*50 + 255*50 + 50)/100, round half up */
        for (p = 0; p < 4; p++) {
            memset(rgb, 0, sizeof rgb);
            draw_blend_white(kQuad[p], 1, 50, rgb);
            for (c = 0; c < 3; c++)
                CHECK(rgb[c] == mix50(kQuad[p][c]));
        }
        /* white at 50 stays white; known mid value: 128 */
        memset(rgb, 0, sizeof rgb);
        draw_blend_white(kQuad[3], 1, 50, rgb);
        CHECK(rgb[0] == 255 && rgb[1] == 255 && rgb[2] == 255);
        memset(rgb, 0, sizeof rgb);
        draw_blend_white(kQuad[2], 1, 50, rgb);   /* blue */
        CHECK(rgb[0] == 128 && rgb[1] == 128 && rgb[2] == 255);

        /* whole 2x2 block at once: same math, contiguous output */
        {
            unsigned char blk[32];
            unsigned char out[24];

            memcpy(blk, kQuad[0], 4);
            memcpy(blk + 4, kQuad[1], 4);
            memcpy(blk + 8, kQuad[2], 4);
            memcpy(blk + 12, kQuad[3], 4);
            memset(out, 0, sizeof out);
            draw_blend_white(blk, 4, 50, out);
            for (p = 0; p < 4; p++)
                for (c = 0; c < 3; c++)
                    CHECK(out[p * 3 + c] == mix50(kQuad[p][c]));
        }

        /* out-of-range opacity clamps to 0..100 */
        memset(rgb, 0, sizeof rgb);
        draw_blend_white(kQuad[0], 1, 150, rgb);
        CHECK(rgb[0] == 255 && rgb[1] == 0 && rgb[2] == 0);
        memset(rgb, 0, sizeof rgb);
        draw_blend_white(kQuad[0], 1, -5, rgb);
        CHECK(rgb[0] == 255 && rgb[1] == 255 && rgb[2] == 255);
    }

    if (g_fail == 0) {
        printf("PASS test_image\n");
        return 0;
    }
    printf("FAIL test_image (%d failures)\n", g_fail);
    return 1;
}
